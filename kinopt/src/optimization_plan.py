"""Build reproducible model, method, and profile comparison plans."""

from dataclasses import dataclass, replace
import re

import numpy as np
from scipy import optimize

from kinopt.src import kinetic_models
from kinopt.src.model_metadata import kinetic_model_metadata
from kinopt.src.optimization_profiles import optimization_profile
from kinopt.src.optimization_runner import LOG_SPACE_LEAST_SQUARES


COMPARISON_LOCAL_METHODS = (
    LOG_SPACE_LEAST_SQUARES,
    "Nelder-Mead",
    "CG",
    "BFGS",
    "L-BFGS-B",
)
_LOCAL_METHOD_DISPLAY_NAMES = {
    LOG_SPACE_LEAST_SQUARES: "Log-space least squares",
    "Nelder-Mead": "Nelder-Mead",
    "CG": "Conjugate gradient",
    "BFGS": "BFGS",
    "L-BFGS-B": "L-BFGS-B",
}


def comparison_method_display_name(method):
    """Return the user-facing name of a comparison-plan method."""
    return _LOCAL_METHOD_DISPLAY_NAMES.get(method, method)


@dataclass(frozen=True)
class ComparisonPlanEntry:
    """One named immutable configuration generated by the assistant."""

    name: str
    rate_model: str
    local_method: str
    profile_name: str
    config: object


def _coerce_profile_value(value):
    if value is None:
        return None
    if value == "Yes":
        return True
    if value == "No":
        return False
    if not isinstance(value, str):
        return value
    if re.fullmatch(r"[+-]?\d+", value):
        return int(value)
    try:
        return float(value)
    except ValueError:
        return value


def _bounded_parameter_metadata(config, rate_metadata):
    metadata = list(rate_metadata.parameters)
    if config.vitrification_law is not None:
        vitrification = kinetic_model_metadata(
            "vitrification",
            config.vitrification_law.__name__,
        )
        if vitrification is None:
            raise ValueError("The selected vitrification model is not supported.")
        metadata.extend(vitrification.parameters)
    if config.coupling_law is not None:
        coupling = kinetic_model_metadata(
            "coupling",
            config.coupling_law.__name__,
        )
        if coupling is None:
            raise ValueError("The selected coupling law is not supported.")
        metadata.extend(coupling.parameters)
    if not all(
        parameter.lower_bound is not None
        and parameter.upper_bound is not None
        for parameter in metadata
    ):
        raise ValueError(
            "Every fitted model parameter needs recommended finite bounds."
        )
    return tuple(metadata)


def _local_method_configuration(method, profile_name, bounds):
    if method not in COMPARISON_LOCAL_METHODS:
        raise ValueError(f"Unsupported comparison method: {method}")
    raw_values = optimization_profile(profile_name).values_for(method)
    values = {
        name: converted
        for name, value in raw_values.items()
        for converted in (_coerce_profile_value(value),)
        if converted is not None
    }
    if method == LOG_SPACE_LEAST_SQUARES:
        values["bounds"] = bounds
        budget = int(values.get("max_nfev", 1))
        return optimize.least_squares, values, budget

    jacobian = values.pop("jac", None)
    options = values
    local_options = {
        "method": method,
        "options": options,
    }
    if method in {"Nelder-Mead", "L-BFGS-B"}:
        local_options["bounds"] = bounds
    if method in {"CG", "BFGS", "L-BFGS-B"}:
        local_options["jac"] = jacobian
    budget = int(options.get("maxiter", 1))
    return optimize.minimize, local_options, budget


def generate_comparison_plan(
    base_config,
    rate_models,
    local_methods,
    profile_names,
    group_name,
):
    """Return the selected model-method-profile cross-product as configs."""
    rate_models = tuple(dict.fromkeys(rate_models))
    local_methods = tuple(dict.fromkeys(local_methods))
    profile_names = tuple(dict.fromkeys(profile_names))
    if not rate_models:
        raise ValueError("Select at least one rate model.")
    if not local_methods:
        raise ValueError("Select at least one local optimization method.")
    if not profile_names:
        raise ValueError("Select at least one calculation profile.")
    if base_config.rate_law is None:
        raise ValueError(
            "The comparison assistant requires a rate model in the current setup."
        )
    if len(rate_models) * len(local_methods) * len(profile_names) > 50:
        raise ValueError("A comparison plan can contain at most 50 jobs.")

    base_guess = np.asarray(base_config.initial_guess, dtype=float)
    tail_guess = base_guess[base_config.rate_parameter_count:]
    normalized_group_name = str(group_name).strip() or "Comparison plan"
    entries = []
    for rate_name in rate_models:
        rate_metadata = kinetic_model_metadata("rate", rate_name)
        if rate_metadata is None:
            raise ValueError(f"Unknown rate model: {rate_name}")
        parameter_metadata = _bounded_parameter_metadata(
            base_config,
            rate_metadata,
        )
        if rate_name == base_config.rate_law.__name__:
            initial_guess = base_guess
        else:
            initial_guess = np.concatenate((
                np.asarray(
                    [
                        float(parameter.example)
                        for parameter in rate_metadata.parameters
                    ]
                ),
                tail_guess,
            ))
        if len(parameter_metadata) != initial_guess.size:
            raise ValueError(
                "The current parameter vector does not match the selected "
                "model metadata."
            )
        bounds = tuple(
            (float(parameter.lower_bound), float(parameter.upper_bound))
            for parameter in parameter_metadata
        )
        lower, upper = np.asarray(bounds, dtype=float).T
        if np.any(initial_guess < lower) or np.any(initial_guess > upper):
            raise ValueError(
                "The current starting values must lie inside the recommended "
                "comparison bounds."
            )

        for method in local_methods:
            for profile_name in profile_names:
                optimizer, options, budget = _local_method_configuration(
                    method,
                    profile_name,
                    bounds,
                )
                config = replace(
                    base_config,
                    initial_guess=initial_guess,
                    global_method="",
                    global_optimizer=None,
                    global_options=None,
                    local_method=method,
                    local_optimizer=optimizer,
                    local_options=options,
                    rate_law=getattr(kinetic_models, rate_name),
                    rate_parameter_count=len(rate_metadata.parameters),
                    max_iterations=budget,
                )
                entries.append(ComparisonPlanEntry(
                    name=(
                        f"{normalized_group_name} - "
                        f"{rate_metadata.display_name} - "
                        f"{comparison_method_display_name(method)} - "
                        f"{profile_name}"
                    ),
                    rate_model=rate_name,
                    local_method=method,
                    profile_name=profile_name,
                    config=config,
                ))
    return tuple(entries)
